/** Serialized Opportunity as delivered by the API (dates as ISO strings). */
export interface OpportunityDTO {
  id: string;
  title: string;
  category: string;
  provider: string;
  sourceType: string;
  description: string;
  eligibility: string;
  benefits: string;
  requiredDocuments: string;
  location: string;
  costType: string;
  minEducation: string;
  fields: string;
  skillsRequired: string;
  deadline: string | null;
  officialUrl: string;
  verificationStatus: string;
  lastVerifiedAt: string;
  createdAt: string;
  updatedAt: string;
}

export interface SessionUser {
  id: string;
  email: string;
  name: string;
  role: string;
}

export interface ProfileDTO {
  educationLevel: string;
  fieldOfStudy: string;
  location: string;
  skills: string;
  interests: string;
  careerGoal: string;
}

export interface RecommendationDTO {
  opportunity: OpportunityDTO;
  score: number;
  reasons: string[];
}

export interface RecommendationsResponse {
  recommendations: RecommendationDTO[];
  source: "ai" | "rules";
  disclaimer: string;
  message?: string;
}

export interface PagedOpportunities {
  items: OpportunityDTO[];
  total: number;
  page: number;
  pageSize: number;
  totalPages: number;
}

export interface StatsDTO {
  total: number;
  verified: number;
  unverified: number;
  expired: number;
  closingSoon: number;
  byCategory: Record<string, number>;
  lastUpdated: string;
}

